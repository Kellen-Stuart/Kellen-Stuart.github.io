function strumSoloEvents(pattern, chords) {
  let chordIndex = 0;

  return [...pattern].map((symbol) => {
    if (symbol === "-") {
      return { hold: true };
    }

    const chord = chords[chordIndex];
    chordIndex += 1;

    return { stroke: "D", chord, accent: /[1-4]/.test(symbol) };
  });
}

