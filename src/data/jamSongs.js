function slugify(value) {
  return value
    .toLowerCase()
    .replace(/&/g, " and ")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/(^-|-$)/g, "");
}

export function createCatalogSong({
  artist,
  title,
  tuning,
  key,
  playedWith = [],
  genres = [],
  hasYousician = false,
  tags = [],
  capo,
  difficulty,
  albumCover,
  summary,
  chart,
}) {
  return {
    ...chart,
    slug: slugify(`${artist}-${title}`),
    artist,
    title,
    tuning,
    ...(key ? { key } : {}),
    ...(capo ? { capo } : {}),
    ...(difficulty ? { difficulty } : {}),
    ...(albumCover ? { albumCover } : {}),
    ...(summary ? { summary } : {}),
    playedWith,
    genres,
    hasYousician,
    tags,
  };
}

