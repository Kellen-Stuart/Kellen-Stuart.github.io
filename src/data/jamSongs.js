export function hasJamSongTab(song) {
  return Boolean(song?.sections?.length);
}

export function getJamSongs() {
  return [...jamSongs].sort((a, b) =>
    `${a.artist} ${a.title}`.localeCompare(`${b.artist} ${b.title}`),
  );
}

export function getJamSongBySlug(slug) {
  return jamSongs.find((song) => song.slug === slug && hasJamSongTab(song));
}
