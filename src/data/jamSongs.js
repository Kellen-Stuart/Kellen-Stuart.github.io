function slugify(value) {
  return value
    .toLowerCase()
    .replace(/&/g, " and ")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/(^-|-$)/g, "");
}

function createCatalogSong({
  artist,
  title,
  tuning,
  guitarKey,
  key,
  tags = [],
  capo,
  difficulty,
  albumCover,
}) {
  return {
    slug: slugify(`${artist}-${title}`),
    artist,
    title,
    tuning,
    guitarKey,
    ...(key ? { key } : {}),
    ...(capo ? { capo } : {}),
    ...(difficulty ? { difficulty } : {}),
    ...(albumCover ? { albumCover } : {}),
    tags,
  };
}

